    private void cargarLibros() {

    LibroDAO dao = new LibroDAO();

    ArrayList<String> libros =
            dao.listarLibrosDisponibles();

    cmbLibroSolicitarPrestamo.removeAllItems();

    for (String libro : libros) {

        cmbLibroSolicitarPrestamo.addItem(libro);
    }
    }
