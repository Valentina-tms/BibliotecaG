    private void btnSolicitarPrestamoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSolicitarPrestamoActionPerformed
        // TODO add your handling code here:
        LibroDAO libroDAO = new LibroDAO();
        PrestamoDAO prestamoDAO = new PrestamoDAO();

        String tituloLibro =
        cmbLibroSolicitarPrestamo
        .getSelectedItem()
        .toString();

        Libro libro =
        libroDAO.buscarPorTitulo(
                tituloLibro
        );

        Prestamo prestamo = new Prestamo(

        0,
        usuario,
        libro,

        txtFechaSolicitarPrestamos.getText(),

        txtFechaLimiteSolicitarPrestamo.getText(),

        null,

        "PENDIENTE"
        );

        boolean registrado =
        prestamoDAO.registrarPrestamo(
                prestamo
        );

        if (registrado) {

        libroDAO.actualizarEstadoLibro(
            libro.getId(),
            "PRESTADO"
        );

        JOptionPane.showMessageDialog(
            this,
            "Préstamo registrado correctamente"
        );

        } else {

        JOptionPane.showMessageDialog(
            this,
            "Error al registrar préstamo"
        );
        }
    }//GEN-LAST:event_btnSolicitarPrestamoActionPerformed

